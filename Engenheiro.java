    public void limpatabela(){
        DefaultTableModel modelo = (DefaultTableModel) Tabela_Engenheiros.getModel();
        Tabela_Engenheiros.getColumnModel().getColumn(0).setPreferredWidth(10);
        Tabela_Engenheiros.getColumnModel().getColumn(1).setPreferredWidth(50);
        Tabela_Engenheiros.getColumnModel().getColumn(2).setPreferredWidth(10);
        Tabela_Engenheiros.getColumnModel().getColumn(3).setPreferredWidth(15);
        
        modelo.setNumRows(0);
    }
    
    public void leTable(){
        //cria variavel para o JTable
        DefaultTableModel modelo = (DefaultTableModel) Tabela_Engenheiros.getModel();
        Tabela_Engenheiros.getColumnModel().getColumn(0).setPreferredWidth(10);
        Tabela_Engenheiros.getColumnModel().getColumn(1).setPreferredWidth(50);
        Tabela_Engenheiros.getColumnModel().getColumn(2).setPreferredWidth(10);
        Tabela_Engenheiros.getColumnModel().getColumn(3).setPreferredWidth(15);
        
        //limpa a consulta anterior
        modelo.setNumRows(0);
        
        DataSource dataSource = new DataSource();
        DaoEngenheiros engDao = new DaoEngenheiros(dataSource);
        
        for(Engenheiros e : engDao.consulta()){
            modelo.addRow (new Object[]{
               e.getIdEngenheiro(),
               e.getDsNome(),
               e.getNrCrea(),
               e.getDtAdmissao()
            });
        }
        
        dataSource.closeDataSource();
    }

